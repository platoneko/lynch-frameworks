#!/usr/bin/env python3
"""000725.SZ (BOE) valuation eval — recompute anchors from frameworks/000725.SZ.md.

formula_id: boe_fy28_consensus_gordon_v3

Whole-company Gordon on the FY2028 consensus (B2): the panel leg is a
commodity-price cyclical, but the 2023 supply restructuring (top-4 mainland
makers > 70% of TV panels, production-to-demand) is a structural break in the
driver, so the mid-cycle numerator is the forward consensus, not a historical
average (valuation-rules「周期票的中枢分子」, sample 600011.SH; user ruling
2026-10-04).  M / H = FY2028E consensus mean / high (Eastmoney, 17 houses),
discounted one year; L = FY2023 measured trough with its measured two-year
recovery (recovery_two_stage_pe).  Multiples are generated by the payout
policy g = (1 - payout) x ROE at basket 6 r = 13%; ROE is FY2028 EPS over the
BPS rolled from 2026H1 with retention 1 - payout.  A tier whose policy g
breaks the cap while ROE <= r + 3pp takes the observed-payout ruler
(capped_payout_pe).  V_opt = 0 (glass-core substrate: no named revenue base).

The doc carries no current price (AGENTS.md「现价 — 禁写契约」), so nothing
here computes a zone or a market-implied r.

Run:  python3 frameworks/eval/000725.SZ.py
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from eval.lib.gordon import (  # noqa: E402
    capped_payout_pe, check_branch, check_g_cap, check_r, g_cap, perpetual_pe, recovery_two_stage_pe,
)
from eval.lib.inputs import (  # noqa: E402
    check_against_stated, check_missing, ladder, parse_baskets, parse_inputs, report,
)
from eval.lib.zones import cut_points  # noqa: E402

FRAMEWORK = REPO_ROOT / "frameworks" / "000725.SZ.md"
FORMULA_ID = "boe_fy28_consensus_gordon_v3"
REQUIRED = [
    "shares", "bps", "ni_2026h1",
    "ni26_m", "ni27_m", "ni28_m", "ni26_h", "ni27_h", "ni28_h", "ni28_lo",
    "ni_l", "ni_l_rec", "n_rec", "payout", "r_perp", "v_opt", "pb_floor",
]


def policy_pe(roe: float, r: float, po: float, dg: float = 0.0) -> tuple[float, float, float]:
    """(PE, g used, g raw) at policy g = (1 - payout) x ROE (+ dg for the sensitivity row)."""
    g_raw = (1 - po) * roe + dg
    cap = g_cap(r)
    if g_raw <= cap:
        return perpetual_pe(g_raw, roe, r), g_raw, g_raw
    if roe <= r + 0.03:
        return capped_payout_pe(g_raw, roe, r, po), cap, g_raw
    return perpetual_pe(cap, roe, r), cap, g_raw


def deck(inp: dict[str, float], dg: float = 0.0) -> dict[str, dict[str, float]]:
    sh, po, r = inp["shares"], inp["payout"], inp["r_perp"]
    out: dict[str, dict[str, float]] = {}
    for t in ("m", "h"):
        eps = inp[f"ni28_{t}"] / sh
        bps = inp["bps"] + (1 - po) * ((inp[f"ni26_{t}"] - inp["ni_2026h1"]) + inp[f"ni27_{t}"]) / sh
        roe = eps / bps
        pe, g, g_raw = policy_pe(roe, r, po, dg)
        out[t] = dict(eps=eps, bps=bps, roe=roe, g=g, g_raw=g_raw, pe=pe, a=eps * pe / (1 + r))
    eps_l = inp["ni_l"] / sh
    n = int(inp["n_rec"])
    g1 = (inp["ni_l_rec"] / inp["ni_l"]) ** (1 / n) - 1
    pe_l = recovery_two_stage_pe(g1, n, out["m"]["g"], out["m"]["roe"], r)
    out["l"] = dict(eps=eps_l, g1=g1, pe=pe_l, a=eps_l * pe_l / (1 + r))
    return out


def main() -> int:
    md = FRAMEWORK.read_text(encoding="utf-8")
    if FORMULA_ID not in md:
        print(f"FAIL: formula_id {FORMULA_ID} missing from framework", file=sys.stderr)
        return 1
    inp = parse_inputs(md)
    errors = check_missing(inp, REQUIRED)
    if errors:
        return report(errors)

    baskets = parse_baskets(md)
    if "r_perp" not in baskets:
        errors.append("r_perp: no 篮 N in the Inputs source cell (valuation-rules.md「§r 篮子」)")
    r, po = inp["r_perp"], inp["payout"]
    errors += check_r(r, "r_perp", baskets.get("r_perp"))

    d = deck(inp)
    L, M, H = (d[t]["a"] for t in ("l", "m", "h"))
    A, B = cut_points(L, M, H)
    errors += ladder("NI28", inp["ni28_lo"], inp["ni28_m"], inp["ni28_h"])
    errors += ladder("anchors", L, M, H)
    for t in ("m", "h"):
        errors += check_g_cap(d[t]["g"], r, f"g_{t}")
        errors += check_branch(d[t]["g"], d[t]["roe"], r, po, f"tier {t.upper()}") if d[t]["g"] == d[t]["g_raw"] else []
    errors += check_against_stated(md, {"L": L, "M": M, "H": H, "A": A, "B": B})
    if inp["v_opt"] != 0:
        errors.append("V_opt must stay 0 (B5) until a named revenue base exists")

    print(f"formula_id={FORMULA_ID}")
    for t in ("m", "h"):
        x = d[t]
        note = f" (raw {x['g_raw']:.2%} capped → payout ruler)" if x["g"] != x["g_raw"] else ""
        print(f"{t.upper()}: EPS28 {x['eps']:.4f} BPS(beg 2028) {x['bps']:.3f} ROE {x['roe']:.2%} "
              f"g {x['g']:.2%}{note} PE {x['pe']:.2f} → /(1+r) = {x['a']:.2f}")
    x = d["l"]
    print(f"L: FY2023 EPS {x['eps']:.4f} g1 {x['g1']:.1%} n {int(inp['n_rec'])} PE {x['pe']:.2f} → /(1+r) = {x['a']:.2f}")
    print(f"L={L:.2f} M={M:.2f} H={H:.2f} A={A:.2f} B={B:.2f}")
    em, eh = d["m"]["eps"], d["h"]["eps"]
    print(f"L/M={L / M:.2f} (分子比 {d['l']['eps'] / em:.2f} x 倍数比 {d['l']['pe'] / d['m']['pe']:.2f}) "
          f"H/M={H / M:.2f} (分子比 {eh / em:.2f} x 倍数比 {d['h']['pe'] / d['m']['pe']:.2f}) "
          f"width={(H - L) / (2 * M):.2f} V_opt/M=0")
    flat = [d["l"]["eps"] * d["m"]["pe"], em * d["m"]["pe"], eh * d["m"]["pe"]]
    errors += ladder("flat-multiple", *flat)
    print(f"flat @ PE_M {d['m']['pe']:.2f}: {flat[0]:.2f}/{flat[1]:.2f}/{flat[2]:.2f}")
    for dg in (-0.01, 0.01):
        s = deck(inp, dg)
        print(f"g ±1pp {dg:+.0%}: L {s['l']['a']:.2f} M {s['m']['a']:.2f} H {s['h']['a']:.2f}")
    lo = inp["ni28_lo"] / inp["shares"]
    print(f"consensus low FY2028 EPS {lo:.4f} x PE_M → {lo * d['m']['pe'] / (1 + r):.2f} (disclosure)")
    print(f"PB floor {inp['pb_floor']}x BPS {inp['bps']} = {inp['pb_floor'] * inp['bps']:.2f} (disclosure only, not max()-ed)")
    print(f"regime coordinate L: FY2023 EPS / r = {d['l']['eps'] / r:.2f}")
    return report(errors)


if __name__ == "__main__":
    sys.exit(main())
