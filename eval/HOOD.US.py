#!/usr/bin/env python3
"""HOOD.US (Robinhood Markets) valuation eval — recompute anchors from frameworks/HOOD.US.md.

frameworks/HOOD.US.md is the source of truth; this script re-derives
L/M/H / A/B / zone from its §3 Inputs table and exits 1 on mismatch.

formula_id: hood_gordon_wholeco_v1

Main ruler: whole-company Gordon on FY2027 consensus EPS.  One leg — the 10-K
reports a single operating segment and discloses no cost by revenue line, so a
sum-of-the-parts would have to invent margins (A2c 反信号).

  M/H: EPS from consensus (mean / high, 22 houses), multiple generated by
       PE = (1 - g2/ROE_x) / (r - g2),  ROE_x = EPS_x * shares / equity
  L:   bottom-up scenario ladder — every line is a measured print (crypto back
       to its FY2023 full-year 135, options/equities back to 2025Q2, net
       interest less the 10-K's own -100bp sensitivity of 304) — then g = 0,
       so the multiple collapses to 1/r.

r is the leg's basket value read from the Inputs row and checked against
gordon.BASKET_R via the 篮 N tag.  A2 records that no basket's written
criterion holds positively and that 篮 4 is the user's ruling, not a derivation.

Axis: mounts _AXIS.crypto-cycle on the L tier only (axis §2b) — crypto is 7.6%
of revenue, so M/H do not consume rung values; the L tier's crypto line must be
this ticker's own measured trough.  The axis L rung is restated in Inputs but
never used in the formula: what the two sides share is the constraint "this
bear is not worse than the axis L", which no arithmetic can verify, so the
restatement is what makes an axis edit force a re-read here.

Run:  python3 frameworks/eval/HOOD.US.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "eval"))

from lib.axes import check_crypto_l_only_mount  # noqa: E402
from lib.gordon import (  # noqa: E402
    check_branch, check_g_cap, check_r, payout_gap, perpetual_pe,
)
from lib.inputs import (  # noqa: E402
    check_against_stated, check_missing, ladder, parse_baskets, parse_inputs, report,
)
from lib.zones import cut_points, zone_of  # noqa: E402
# rf_report imports `eval.lib.*`, so the repo root must be importable too.
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from eval.lib.bands_io import write_rf_readings  # noqa: E402
from eval.lib.rf_report import rf_block  # noqa: E402

FRAMEWORK = Path(__file__).resolve().parents[2] / "frameworks" / "HOOD.US.md"
FORMULA_ID = "hood_gordon_wholeco_v1"
# _AXIS.rates segment: a US listing reads the USD r_f (valuation-rules「按上市货币取段」).
LISTING_CCY = "USD"

REQUIRED = [
    "price", "shares", "equity",
    "eps_27_l", "eps_27_m", "eps_27_h", "eps_28_ms",
    "opt_l", "pred_l", "eq_l", "crypto_l", "othtx_l", "nii_l", "othrev_l",
    "opex_l", "nii_shock_100", "tax",
    "r_op", "g2", "g2_l", "crypto_trough", "axis_ebitda_l", "payout_obs",
    "seller_tp_mean", "seller_tp_lo", "seller_tp_hi",
]

# The L tier's revenue lines, in the order the framework's 表1 narrates them.
L_REVENUE_LINES = ("opt_l", "pred_l", "eq_l", "crypto_l", "othtx_l", "nii_l", "othrev_l")

# A4: the legal outcome for event contracts is not a measured state, so it stays
# out of the base L and is printed as a sensitivity instead.
PRED_ZERO_SENSITIVITY = "pred_l"


def main() -> int:
    md = FRAMEWORK.read_text(encoding="utf-8")
    inp = parse_inputs(md)
    errors = check_missing(inp, REQUIRED)
    if errors:
        return report(errors)

    r, g2, g2_l = inp["r_op"], inp["g2"], inp["g2_l"]
    shares, equity, tax = inp["shares"], inp["equity"], inp["tax"]

    # --- guards that are about the ruler, not the arithmetic -----------------
    baskets = parse_baskets(md)
    errors += check_r(r, "r_op", baskets.get("r_op"))
    errors += check_g_cap(g2, r, "g2")
    errors += check_crypto_l_only_mount(
        inp["crypto_l"], inp["crypto_trough"], inp["axis_ebitda_l"]
    )

    # --- 1) L numerator: bottom-up ladder ------------------------------------
    rev_l = sum(inp[k] for k in L_REVENUE_LINES)
    ni_l = (rev_l - inp["opex_l"]) * (1 - tax)
    eps_l = ni_l / shares

    # --- 2) M/H numerators: consensus ----------------------------------------
    eps_m, eps_h = inp["eps_27_m"], inp["eps_27_h"]
    ni_m, ni_h = eps_m * shares, eps_h * shares

    # --- 3) forward ROE per tier, on the one `equity` field ------------------
    roe_l, roe_m, roe_h = ni_l / equity, ni_m / equity, ni_h / equity

    # --- 4) multiples --------------------------------------------------------
    # L runs g = 0 as a *scenario* (growth switched off), not as a payout
    # policy, so check_branch is not the right test for it — only M/H are
    # generated by a g the company has to fund out of retention.
    def multiples(r_: float) -> tuple[float, float, float]:
        pe_l_ = 1.0 / r_ if g2_l == 0 else perpetual_pe(g2_l, roe_l, r_)
        return pe_l_, perpetual_pe(g2, roe_m, r_), perpetual_pe(g2, roe_h, r_)

    pe_l, pe_m, pe_h = multiples(r)
    errors += check_branch(g2, roe_m, r, inp["payout_obs"], "M")

    # --- 5) anchors ----------------------------------------------------------
    L, M, H = eps_l * pe_l, eps_m * pe_m, eps_h * pe_h
    errors += ladder("eps", eps_l, eps_m, eps_h)
    errors += ladder("anchor", L, M, H)
    # A2e-2c: the ladder must already hold on the numerators alone.
    errors += ladder("flat-multiple", eps_l * pe_m, eps_m * pe_m, eps_h * pe_m)

    A, B = cut_points(L, M, H)
    zone = zone_of(inp["price"], L, M, H)
    errors += check_against_stated(md, {"L": L, "M": M, "H": H, "A": A, "B": B}, zone)

    # --- disclosure ----------------------------------------------------------
    modelled_payout, gap = payout_gap(g2, roe_m, inp["payout_obs"])
    eps_28 = inp["eps_28_ms"]
    roe_28 = eps_28 * shares / equity
    cand_m = eps_28 * perpetual_pe(g2, roe_28, r)
    implied_r = g2 + (1 - g2 / roe_m) / (inp["price"] / eps_m)
    # A4 prints two readings because the sports share of event-contract revenue
    # is not disclosed: half as a proxy for a sports-only ban, and the whole line.
    def eps_l_less_pred(share: float) -> float:
        return (rev_l - inp[PRED_ZERO_SENSITIVITY] * share - inp["opex_l"]) * (1 - tax) / shares

    eps_l_half, eps_l_zero = eps_l_less_pred(0.5), eps_l_less_pred(1.0)

    print(f"formula_id {FORMULA_ID}")
    print(f"  L rev {rev_l:.0f}  NI_L {ni_l:.1f}  EPS  {eps_l:.4f} / {eps_m:.4f} / {eps_h:.4f}")
    print(f"  ROE   {roe_l:.2%} / {roe_m:.2%} / {roe_h:.2%}   (r {r:.0%}, g2 {g2:.0%})")
    print(f"  PE    {pe_l:.2f}x / {pe_m:.2f}x / {pe_h:.2f}x")
    print(f"  L/M/H {L:.2f} / {M:.2f} / {H:.2f}   A {A:.2f}  B {B:.2f}  zone {zone}")
    print(f"  ratios L/M {L / M:.3f}  H/M {H / M:.3f}  (H-L)/2M {(H - L) / (2 * M):.1%}")
    print(f"  candidate M' {cand_m:.2f} (MS FY2028 {eps_28}, single house)")
    print(f"  implied r(P) {implied_r:.2%}  vs basket {r:.0%}  delta {implied_r - r:+.2%}")
    print(f"  payout modelled {modelled_payout:.1%} vs observed {inp['payout_obs']:.1%} gap {gap:+.1%}")
    print(f"  A4 sensitivity: prediction markets halved -> L {eps_l_half * pe_l:.2f}"
          f"  |  zeroed -> L {eps_l_zero * pe_l:.2f}")

    # r_f readings (_AXIS.rates, valuation-rules「利率轴与 r_f 敏感性」): Δr_f moves
    # r_op 1:1 in all three multiples; numerators, ROE and g stay put.
    # Disclosure only — the anchors above are the 中枢 column.
    def band_at(dr: float) -> tuple[float, float, float]:
        pl, pm, ph = multiples(r + dr)
        return eps_l * pl, eps_m * pm, eps_h * ph

    rf = rf_block(LISTING_CCY, {"r_op": r}, band_at, inp["price"])
    # Only a clean run feeds the daily digest.
    if not errors:
        write_rf_readings("HOOD.US", rf.seg, (L, M, H), rf.consensus, rf.pressure)
    return report(errors)


if __name__ == "__main__":
    raise SystemExit(main())
