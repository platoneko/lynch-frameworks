#!/usr/bin/env python3
"""2631.HK (SICC) valuation eval — asset-PB bottom + ASP-fullcap success option.

frameworks/2631.HK.md is the source of truth; this script recomputes
bottom L/M/H / A/B / zone / V_opt and exits 1 on mismatch.

formula_id (bottom): sicc_asset_pb_bottom_v1
formula_id (option): sicc_asp_fullcap_success_vopt_v3_ipo_anchor

Bottom = PB 0.55/0.80/1.00 × BPS (no ASP repair), BPS = equity × fx / shares.
Option (vopt_v3_ipo_anchor): the success world (full capacity × ASP repair)
has no computable post-ramp numerator — consensus stops at 2028E mid-ramp and
the post-ramp margin is unmeasured — so its value is NOT generated by Gordon.
The ceiling is the ticker's one external valuation event, the H-share IPO
price (A11): V_opt = max(0, ipo_price − H); 表3 = base_k + p_k × V_opt with
P_K an eval constant, never an Input (A2e-7a).

Gordon on realised units (post-ramp nameplate × ASP 2024 × margin 2024,
`perpetual_pe` with ROE_H < r pinned at 1/r, discounted from 2030) is printed
as a CROSS-CHECK only (A6): it shows the ROE gate, not the option's value.

r is the basket rate (A14): the whole company sits in 篮 7 单押 / 故事 15%,
`r_perp` / `r_disc` are read from Inputs and `check_r` requires the value to
match the basket the source cell names (`parse_baskets`).  The basket touches
only the cross-check and the earnings-ruler reference; the asset-PB bottom and
the IPO-price option ceiling carry no r.  The 篮 7 steady-state floor
(1/r × E) is printed as a disclosure and never max()-ed into L.

Earnings-ruler reference (A2e-1 asset_play row): consensus NP × the same Gordon
multiple, printed and required to sit below L — if it ever exceeds L the asset
ruler is no longer the upper bound and the framework goes back to dialogue.

Run:  python3 frameworks/eval/2631.HK.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from eval.lib.gordon import check_g_cap, check_r, perpetual_pe, two_stage_pe  # noqa: E402
from eval.lib.inputs import (  # noqa: E402
    check_against_stated,
    check_missing,
    ladder,
    outputs_section,
    parse_baskets,
    parse_inputs,
    report,
)
from eval.lib.zones import cut_points, zone_of  # noqa: E402

FRAMEWORK = REPO_ROOT / "frameworks" / "2631.HK.md"
FORMULA_IDS = (
    "sicc_asset_pb_bottom_v1",
    "sicc_asp_fullcap_success_vopt_v3_ipo_anchor",
)
# 表3 per-tier credit (A12): 拍值, no external anchor. Never an Input, never the base.
P_K = (0.0, 0.25, 1.0)
KPCS = 1e4
YI = 1e8

REQUIRED = [
    "price", "shares", "fx_cny_hkd", "equity_cny",
    "pb_l", "pb_m", "pb_h",
    "ipo_price_hkd", "close_own_min", "close_own_median",
    "cap_kpcs", "vol_unit_kpcs", "rev_basis_up", "asp_h", "m_h", "m_h_old",
    "g2_opt", "r_perp", "r_disc", "year_now", "t_fullcap",
    "np26e_cny", "np27e_cny", "np28e_cny",
    "pb_own_min", "pb_own_max",
]


def stated_v_opt(md: str) -> float | None:
    sec = outputs_section(md)
    m = re.search(r"V_\{opt\}\D{0,20}\*\*([0-9.]+)\*\*", sec)
    return float(m.group(1)) if m else None


def gordon_cross(inp: dict[str, float], vol_kpcs: float, margin: float, discount: bool) -> dict[str, float]:
    """Success world on realised units × Gordon, HKD/share — cross-check only (A6)."""
    rev = vol_kpcs * KPCS * inp["asp_h"] * inp["rev_basis_up"]
    np_h = rev * margin
    roe = np_h / (inp["equity_cny"] * YI)
    pe = perpetual_pe(inp["g2_opt"], roe, inp["r_perp"])
    years = inp["t_fullcap"] - inp["year_now"]
    disc = (1.0 + inp["r_disc"]) ** (-years) if discount else 1.0
    return {"rev": rev, "np": np_h, "roe": roe, "pe": pe, "disc": disc,
            "v": pe * np_h * inp["fx_cny_hkd"] / inp["shares"] * disc}


def main() -> int:
    md = FRAMEWORK.read_text(encoding="utf-8")
    errors: list[str] = []
    for fid in FORMULA_IDS:
        if fid not in md:
            errors.append(f"formula_id {fid} missing from framework")

    inp = parse_inputs(md)
    errors += check_missing(inp, REQUIRED)
    if errors and any(e.startswith("missing") or "formula_id" in e for e in errors):
        return report(errors)

    # r must be the basket value named in the Inputs source cell (A14); r_disc
    # carries no basket tag and only has to be a basket-table value.
    baskets = parse_baskets(md)
    if "r_perp" not in baskets:
        errors.append("r_perp: no 篮 N in the Inputs source cell (A14)")
    errors += check_r(inp["r_perp"], "r_perp", baskets.get("r_perp"))
    errors += check_r(inp["r_disc"], "r_disc", baskets.get("r_disc"))
    if abs(inp["r_disc"] - inp["r_perp"]) > 1e-9:
        errors.append(f"r_disc {inp['r_disc']} != r_perp {inp['r_perp']}: the discount year uses the same basket r (A2 / A14)")
    errors += check_g_cap(inp["g2_opt"], inp["r_perp"], "g2_opt")
    if not (inp["pb_l"] < inp["pb_m"] < inp["pb_h"]):
        errors.append(f"pb order violated: {inp['pb_l']}/{inp['pb_m']}/{inp['pb_h']}")
    leaked = [k for k in inp if k == "p" or k.startswith("p_")]
    if leaked:
        errors.append(f"p-class fields in Inputs (A2e-7a): {leaked}")

    # --- bottom card: asset PB ------------------------------------------------
    bps = inp["equity_cny"] * YI * inp["fx_cny_hkd"] / inp["shares"]
    L = inp["pb_l"] * bps
    M = inp["pb_m"] * bps
    H = inp["pb_h"] * bps
    A, B = cut_points(L, M, H)
    zone = zone_of(inp["price"], L, M, H)

    # --- option: IPO price as the success-world ceiling (A11) -----------------
    v_top = inp["ipo_price_hkd"]
    v_opt = max(0.0, v_top - H)
    adj = [x + p * v_opt for x, p in zip((L, M, H), P_K)]
    adj_a, adj_b = cut_points(*adj)
    adj_zone = zone_of(inp["price"], *adj)

    # --- Gordon cross-check on realised units (A6): the ROE gate, not the value
    post = gordon_cross(inp, inp["cap_kpcs"], inp["m_h"], discount=True)
    sens = {
        "post-ramp undisc": gordon_cross(inp, inp["cap_kpcs"], inp["m_h"], discount=False),
        "pre-ramp k=1": gordon_cross(inp, inp["vol_unit_kpcs"], inp["m_h"], discount=True),
        "nameplate+17%": gordon_cross(inp, inp["cap_kpcs"], inp["m_h_old"], discount=True),
        "nameplate+17%+undisc": gordon_cross(inp, inp["cap_kpcs"], inp["m_h_old"], discount=False),
    }

    # --- earnings-ruler reference (A2e-1 asset_play row) ----------------------
    ref = {}
    for label, key, years in (("2026E", "np26e_cny", 0), ("2027E", "np27e_cny", 0), ("2028E", "np28e_cny", 2)):
        np_y = inp[key] * YI
        roe = np_y / (inp["equity_cny"] * YI)
        pe = perpetual_pe(0.0, roe, inp["r_perp"])
        disc = (1.0 + inp["r_disc"]) ** (-years)
        ref[label] = {"roe": roe, "pe": pe, "v": pe * np_y * inp["fx_cny_hkd"] / inp["shares"] * disc}
    g1 = inp["np28e_cny"] / inp["np27e_cny"] - 1.0
    roe27 = ref["2027E"]["roe"]
    two_stage = two_stage_pe(g1, 1, 0.0, roe27, inp["r_perp"])

    print(f"formula_id: {FORMULA_IDS[0]} + {FORMULA_IDS[1]}")
    print(f"bottom     BPS {bps:.3f} HKD (equity {inp['equity_cny']:.2f} 亿 CNY x fx {inp['fx_cny_hkd']})"
          f"  PB={inp['pb_l']:g}/{inp['pb_m']:g}/{inp['pb_h']:g}")
    print(f"base L={L:.2f} M={M:.2f} H={H:.2f}  A={A:.2f} B={B:.2f}")
    print(f"L/M={L / M:.2f} H/M={H / M:.2f} (H-L)/2M={(H - L) / (2 * M):.0%}  V_opt/M={v_opt / M:.1%}")
    print(f"decompose  L/M = num 1.000 x pb {inp['pb_l'] / inp['pb_m']:.3f} | H/M = num 1.000 x pb "
          f"{inp['pb_h'] / inp['pb_m']:.3f}  (asset ruler; flat ladder == base)")
    print(f"own PB band [{inp['pb_own_min']}, {inp['pb_own_max']}] (H-share realised) vs deck "
          f"{inp['pb_l']}-{inp['pb_h']}: deck entirely below the band; price/BPS {inp['price'] / bps:.2f}x")
    print(f"option     ceiling = IPO price {v_top:.2f} HKD (2025-08-20) -> V_opt {v_opt:.2f}  "
          f"(own closes since IPO: min {inp['close_own_min']:g} / median {inp['close_own_median']:g})")
    print(f"表3  p_k={P_K[0]:.2f}/{P_K[1]:.2f}/{P_K[2]:.2f}  L'/M'/H' = {adj[0]:.2f}/{adj[1]:.2f}/{adj[2]:.2f}  "
          f"A'={adj_a:.2f} B'={adj_b:.2f}  zone+V = {adj_zone}")
    print(f"     市价隐含 p = {(inp['price'] - H) / v_opt:.2f}; P/(H+V) = {inp['price'] / adj[2] - 1:+.1%}; "
          f"anchor -> own min close {inp['close_own_min']:g}: V_opt {max(0.0, inp['close_own_min'] - H):.2f}")
    print(f"gordon x-check post-ramp {inp['cap_kpcs']:g} 万片 x ASP {inp['asp_h']:g} x {inp['rev_basis_up']} x margin {inp['m_h']:.3f}: "
          f"rev {post['rev'] / YI:.2f}亿 np {post['np'] / YI:.2f}亿 roe {post['roe']:.2%} pe {post['pe']:.2f} "
          f"disc {post['disc']:.3f} -> V^G_H {post['v']:.2f} HKD (< ceiling {v_top:.2f}: ROE gate, A6)")
    for name, s in sens.items():
        print(f"  sens {name:22s}: np {s['np'] / YI:.2f}亿 roe {s['roe']:.2%} pe {s['pe']:.2f} V^G_H {s['v']:.2f}")
    print("earnings ruler ref (consensus NP x Gordon, ROE<r -> 1/r): "
          + " / ".join(f"{k} {x['v']:.2f} (roe {x['roe']:.1%})" for k, x in ref.items())
          + f"  | all < L {L:.2f}: {all(x['v'] < L for x in ref.values())}")
    print(f"two-stage lever (g1 {g1:+.1%} x1y on 2027E, roe {roe27:.1%}): stage-1 payout {1 - g1 / roe27:+.1f}, "
          f"multiple {two_stage:.2f} -> degenerate, unavailable")
    margin_gate = inp["r_perp"] * inp["equity_cny"] * YI / post["rev"]
    g2_sens = perpetual_pe(0.01, post["roe"], inp["r_perp"])
    print(f"r_perp {inp['r_perp']:g} (篮 {baskets.get('r_perp')}), cross-check only; ROE gate: post-ramp margin must be "
          f">= {margin_gate:.1%} for ROE_H > r; g2 0 -> 1% at roe {post['roe']:.1%}: pe {g2_sens:.2f}")
    print(f"篮 {baskets.get('r_perp')} floor 1/r x E (disclosure, not max()-ed): "
          + " / ".join(f"{k} {x['v']:.2f}" for k, x in ref.items()) + f"  | L stays {L:.2f}")
    print(f"表2  price {inp['price']} -> zone = {zone}   P/H {inp['price'] / H:.2f}x")

    errors += check_against_stated(md, {"L": L, "M": M, "H": H, "A": A, "B": B}, zone, tol=0.05)
    errors += ladder("base", L, M, H)
    if v_opt < 0:
        errors.append(f"V_opt must be >= 0, got {v_opt:.2f}")
    said_v = stated_v_opt(md)
    if said_v is None:
        errors.append("stated V_opt not found in Outputs")
    elif abs(said_v - v_opt) > 0.05:
        errors.append(f"V_opt: stated {said_v} vs recomputed {v_opt:.4f}")
    if abs(adj[0] - L) > 1e-9:
        errors.append(f"p leaked into the base: 表3 L row {adj[0]:.4f} != base L {L:.4f}")
    if not all(x["v"] < L for x in ref.values()):
        errors.append("earnings-ruler reference exceeds L: the asset ruler is no longer the upper bound — back to dialogue")
    if v_opt > 0 and "表3" not in outputs_section(md):
        errors.append("V_opt > 0 but Outputs has no 表3")
    if abs(v_top - inp["price"]) < 1e-9 or abs(v_top - inp["close_own_median"]) < 1e-9:
        errors.append("ipo_price_hkd equals the current price / own median: the anchor must be the IPO print, not a price input (A11)")

    return report(errors)


if __name__ == "__main__":
    sys.exit(main())
